import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const contentDirectory = path.join(root, "content", "legal");
const outputFile = path.join(root, "app", "legal", "generated-content.ts");
const requiredDocuments = ["terms", "privacy", "accuracy", "fraud-awareness", "authorization", "report"];

function parseDocument(source, filename) {
  source = source.replace(/\r\n/g, "\n");
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`${filename} must start with frontmatter delimited by --- lines.`);

  const frontmatter = Object.fromEntries(match[1].split(/\r?\n/).filter(Boolean).map((line) => {
    const separator = line.indexOf(":");
    if (separator < 1) throw new Error(`${filename} has invalid frontmatter: ${line}`);
    return [line.slice(0, separator).trim(), line.slice(separator + 1).trim()];
  }));
  for (const field of ["id", "route", "title", "summary", "versionLabel", "reviewStatus", "updated"]) {
    if (!frontmatter[field]) throw new Error(`${filename} is missing frontmatter field ${field}.`);
  }
  if (!frontmatter.route.startsWith("/legal/")) throw new Error(`${filename} route must be under /legal/.`);
  if (/\[(?:INSERT|CONTACT|ADDRESS|NAME|DATE)[A-Z _-]*\]|\bTBD\b|\bTODO\b|placeholder/i.test(match[2])) {
    throw new Error(`${filename} contains an unresolved placeholder.`);
  }
  return { ...frontmatter, body: match[2].trim() };
}

const filenames = (await readdir(contentDirectory)).filter((name) => name.endsWith(".md")).sort();
const documents = {};
for (const filename of filenames) {
  const document = parseDocument(await readFile(path.join(contentDirectory, filename), "utf8"), filename);
  if (documents[document.id]) throw new Error(`Duplicate legal document id: ${document.id}`);
  documents[document.id] = document;
}
for (const id of requiredDocuments) {
  if (!documents[id]) throw new Error(`Missing legal document: ${id}`);
}

const termsVersion = documents.terms.termsVersion;
const disclaimerVersion = documents.accuracy.disclaimerVersion;
const accuracyUrl = documents.accuracy.publicUrl;
if (!termsVersion || !disclaimerVersion || !accuracyUrl) {
  throw new Error("Terms and accuracy frontmatter must define termsVersion, disclaimerVersion, and publicUrl.");
}
new URL(accuracyUrl);

const output = `// Generated by scripts/generate-legal-content.mjs. Edit content/legal/*.md instead.\n` +
  `export type LegalDocument = { id: string; route: string; title: string; summary: string; versionLabel: string; reviewStatus: string; updated: string; termsVersion?: string; disclaimerVersion?: string; publicUrl?: string; body: string };\n\n` +
  `export const LEGAL_DOCUMENTS = ${JSON.stringify(documents, null, 2)} as const satisfies Record<string, LegalDocument>;\n\n` +
  `export const LEGAL_VERSIONS = ${JSON.stringify({ termsVersion, disclaimerVersion }, null, 2)} as const;\n` +
  `export const LEGAL_ACCURACY_URL = ${JSON.stringify(accuracyUrl)};\n`;

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, output, "utf8");
console.log(`Generated ${path.relative(root, outputFile)} from ${filenames.length} versioned legal documents.`);
