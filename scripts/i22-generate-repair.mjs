/**
 * I-22 repair generator.
 *
 * The live D1 database was created by the runtime CREATE TABLE IF NOT EXISTS
 * bootstrap, which declared bare `PRIMARY KEY` on five TEXT id columns. SQLite
 * allows NULL in a TEXT PRIMARY KEY, so those columns are unconstrained in the
 * deployed database. CREATE TABLE IF NOT EXISTS cannot repair an existing
 * table, so the fix is a table rebuild.
 *
 * This generator derives the rebuild from SCHEMA_BOOTSTRAP_SQL rather than
 * hand-copied DDL, so the repair can never drift from the schema authority.
 *
 * authorization_audit_events is deliberately excluded: its id is
 * INTEGER PRIMARY KEY AUTOINCREMENT, which is the rowid alias and cannot store
 * NULL. tests/schema-repair.test.mjs proves that rather than assuming it.
 */
import { writeFile } from "node:fs/promises";
import { SCHEMA_BOOTSTRAP_SQL } from "../app/lib/schema-bootstrap.ts";

export const TABLES_NEEDING_REPAIR = [
  "authorization_requests",
  "provider_verifications",
  "imported_vehicles",
  "creative_projects",
  "creative_render_jobs",
];

const createStatements = new Map();
const indexStatements = new Map();

for (const statement of SCHEMA_BOOTSTRAP_SQL) {
  const create = statement.match(/CREATE TABLE IF NOT EXISTS (\w+)/);
  if (create) {
    createStatements.set(create[1], statement);
    continue;
  }
  const index = statement.match(/CREATE INDEX IF NOT EXISTS \w+ ON (\w+)\(/);
  if (index) {
    const list = indexStatements.get(index[1]) ?? [];
    list.push(statement);
    indexStatements.set(index[1], list);
  }
}

/** Column names in declaration order, skipping table-level constraints. */
export function columnsOf(ddl) {
  const body = ddl.slice(ddl.indexOf("(") + 1, ddl.lastIndexOf(")"));
  const columns = [];
  let depth = 0;
  let current = "";
  for (const char of body) {
    if (char === "(") depth += 1;
    if (char === ")") depth -= 1;
    if (char === "," && depth === 0) {
      columns.push(current);
      current = "";
      continue;
    }
    current += char;
  }
  columns.push(current);
  return columns
    .map((entry) => entry.trim())
    .filter(Boolean)
    .filter((entry) => !/^(PRIMARY|UNIQUE|CHECK|FOREIGN|CONSTRAINT)\b/i.test(entry))
    .map((entry) => entry.split(/\s+/)[0].replace(/[`"]/g, ""));
}

export function repairStatementsFor(table) {
  const ddl = createStatements.get(table);
  if (!ddl) throw new Error(`No bootstrap DDL for ${table}`);
  const staging = `${table}__i22`;
  const columns = columnsOf(ddl).join(", ");
  return [
    ddl.replace("CREATE TABLE IF NOT EXISTS " + table, `CREATE TABLE ${staging}`),
    `INSERT INTO ${staging} (${columns}) SELECT ${columns} FROM ${table}`,
    `DROP TABLE ${table}`,
    `ALTER TABLE ${staging} RENAME TO ${table}`,
    ...(indexStatements.get(table) ?? []),
  ];
}

export function repairStatements() {
  return TABLES_NEEDING_REPAIR.flatMap(repairStatementsFor);
}

const header = `-- I-22: enforce NOT NULL on TEXT PRIMARY KEY columns in an existing database.
--
-- GENERATED by scripts/i22-generate-repair.mjs from SCHEMA_BOOTSTRAP_SQL.
-- Do not edit by hand; regenerate instead.
--
-- These statements are DESTRUCTIVE (DROP TABLE after copy). Take a D1 export
-- before applying. Apply as a single batch so the copy and swap are atomic.
-- Applying this to production requires Joe's approval and is not automated.
`;

// Only writes when run as a CLI. Importing this module (from tests) is side-effect free.
if (process.argv[1]?.endsWith("i22-generate-repair.mjs")) {
  const sql = header + "\n" + repairStatements().map((s) => `${s.trim()};`).join("\n\n") + "\n";
  const target = new URL("../drizzle/repair/i22-enforce-pk-not-null.sql", import.meta.url);
  await writeFile(target, sql, "utf8");
  console.log(`Wrote ${repairStatements().length} statements to drizzle/repair/i22-enforce-pk-not-null.sql`);
}
